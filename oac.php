          <li>Identificación de domicilio o residencia y número de teléfono.</li>
          <li>Narración circunstanciada del hecho.</li>
          <li>Identificación del denunciado.</li>
          <li>Descripción técnica de la obra.</li>
          <li>En caso de tener soportes, anexar copias.</li>
        </ol>
        <p style="margin-top:16px;"><strong>Nota:</strong> no se admitirán denuncias anónimas.</p>
        <p style="margin-top:16px;">
          Todo ciudadano podrá presentar las denuncias que estime pertinente cuando tenga
          conocimiento de que funcionarios públicos o particulares se encuentren involucrados en
          algún hecho irregular, relacionado con el manejo de fondos o bienes públicos pertenecientes
          a las entidades sujetas al control, siempre y cuando estén debidamente fundadas.
        </p>
      </div>

      <div class="panel-info" style="margin-top:40px;">
        <h3>¿Qué sanciones impone la Contraloría del Municipio Ambrosio Plaza?</h3>
        <p>Al comprobarse las irregularidades cometidas por una persona que maneje recursos públicos, la Contraloría del Municipio Ambrosio Plaza puede:</p>
        <ul class="lista-puntos">
          <li>Imponer multas.</li>
          <li>Imponer reparo: la reposición del dinero mal empleado por el presunto implicado, cuando existen daños al patrimonio del Municipio.</li>
          <li>Remitir las actuaciones al Ministerio Público en los casos de responsabilidad penal.</li>
        </ul>
      </div>
